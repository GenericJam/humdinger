#!/usr/bin/env python3
"""Extract the music glyphs the PDF engraver draws from Noto Music.

Reads priv/fonts/NotoMusic-Regular.ttf and writes lib/humdinger/music_glyphs.ex:
each glyph's TrueType outline as move/line/quadratic/close path data in font
units, with its advance width and bounding box, plus the font's staff metrics
(read from its five-line staff glyph, U+1D11A) so the engraver can scale the
glyphs to its own staff.

Usage (from the project root; needs fontTools):

    python3 scripts/extract_music_glyphs.py

The output is laid out the way `mix format` would, so regenerating it leaves
the formatter with nothing to do.
"""

import sys
from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "priv/fonts/NotoMusic-Regular.ttf"
OUT = ROOT / "lib/humdinger/music_glyphs.ex"

STAFF = 0x1D11A

# name, codepoint
GLYPHS = [
    ("treble_clef", 0x1D11E),
    ("bass_clef", 0x1D122),
    ("sharp", 0x266F),
    ("flat", 0x266D),
    ("natural", 0x266E),
    ("whole_rest", 0x1D13B),
    ("half_rest", 0x1D13C),
    ("quarter_rest", 0x1D13D),
    ("eighth_rest", 0x1D13E),
    ("sixteenth_rest", 0x1D13F),
    # Combining flags: drawn for an up stem whose tip is at y = 1009, the flag's
    # left edge on the stem's left edge.
    ("flag_eighth", 0x1D16E),
    ("flag_sixteenth", 0x1D16F),
]


def num(v):
    """Font units as the shortest exact literal (TrueType implied points can be .5)."""
    r = round(v * 2) / 2
    return str(int(r)) if r == int(r) else str(r)


def path_literal(path):
    """The path string after `path:`, wrapped onto its own line the way `mix format` does."""
    one_line = f' "{path}"'
    return one_line if len("      path:" + one_line) <= 98 else f'\n        "{path}"'


class PathPen(BasePen):
    """Records an outline as `M x y`, `L x y`, `Q x1 y1 x y`, `Z` path data."""

    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.parts = []

    def _moveTo(self, pt):
        self.parts.append("M" + " ".join(map(num, pt)))

    def _lineTo(self, pt):
        self.parts.append("L" + " ".join(map(num, pt)))

    def _qCurveToOne(self, pt1, pt2):
        self.parts.append("Q" + " ".join(map(num, (*pt1, *pt2))))

    def _curveToOne(self, pt1, pt2, pt3):
        raise ValueError("cubic segment in a TrueType outline")

    def _closePath(self):
        self.parts.append("Z")

    def _endPath(self):
        raise ValueError("open contour")


def staff_metrics(font):
    """Line thickness, bottom-line centre and line spacing of the staff glyph."""
    glyf = font["glyf"]
    glyph = glyf[font.getBestCmap()[STAFF]]
    coords, ends, _ = glyph.getCoordinates(glyf)
    lines = []
    start = 0
    for end in ends:
        ys = [y for _, y in coords[start : end + 1]]
        lines.append((min(ys), max(ys)))
        start = end + 1
    lines.sort()
    if len(lines) != 5:
        raise ValueError(f"staff glyph has {len(lines)} contours, expected 5")
    thickness = lines[0][1] - lines[0][0]
    centres = [(lo + hi) / 2 for lo, hi in lines]
    spaces = {centres[i + 1] - centres[i] for i in range(4)}
    if len(spaces) != 1:
        raise ValueError(f"uneven staff spacing {spaces}")
    return thickness, centres[0], spaces.pop()


def main():
    font = TTFont(FONT)
    cmap = font.getBestCmap()
    missing = [f"{name} U+{cp:04X}" for name, cp in GLYPHS + [("staff", STAFF)] if cp not in cmap]
    if missing:
        sys.exit("not in the font: " + ", ".join(missing))

    upem = font["head"].unitsPerEm
    thickness, bottom, space = staff_metrics(font)
    glyph_set = font.getGlyphSet()
    glyf = font["glyf"]

    entries = []
    for name, cp in GLYPHS:
        gname = cmap[cp]
        pen = PathPen(glyph_set)
        glyph_set[gname].draw(pen)
        g = glyf[gname]
        g.recalcBounds(glyf)
        advance = font["hmtx"][gname][0]
        entries.append(
            f"    {name}: %{{\n"
            f"      codepoint: 0x{cp:X},\n"
            f"      advance: {advance},\n"
            f"      bbox: {{{g.xMin}, {g.yMin}, {g.xMax}, {g.yMax}}},\n"
            f"      path:{path_literal(''.join(pen.parts))}\n"
            f"    }}"
        )

    OUT.write_text(TEMPLATE.format(
        upem=upem,
        thickness=num(thickness),
        bottom=num(bottom),
        space=num(space),
        entries=",\n".join(entries),
    ))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(GLYPHS)} glyphs")


TEMPLATE = '''# Generated by scripts/extract_music_glyphs.py from
# priv/fonts/NotoMusic-Regular.ttf (SIL Open Font License, priv/fonts/OFL.txt).
# Do not edit by hand. Regenerate from the project root with:
#
#     python3 scripts/extract_music_glyphs.py
defmodule Humdinger.MusicGlyphs do
  @moduledoc """
  Outlines of the Noto Music glyphs the PDF engraver draws: clefs,
  accidentals, rests and flags. Embedding a font in a PDF is far more code
  than drawing its few glyphs as paths, so the outlines are copied here.

  Coordinates are font units ({upem} per em), y up. The font's own staff
  glyph has its bottom line centred at `staff_bottom/0`, lines
  `staff_space/0` apart, so scaling a glyph by `space / staff_space()` and
  putting its `staff_bottom/0` on a staff's bottom line positions it as the
  font intends: clefs curl round their line, accidentals centre on a note in
  the first space, rests sit in the staff. Flags hang from an up stem whose
  tip is at y = 1009, their left edge on the stem's left edge.

  Path ops are `{{:m, x, y}}`, `{{:l, x, y}}`, `{{:q, cx, cy, x, y}}` (TrueType
  quadratic from the current point) and `:z`; every contour is closed.
  """

  @type op ::
          {{:m, number, number}}
          | {{:l, number, number}}
          | {{:q, number, number, number, number}}
          | :z
  @type glyph :: %{{
          codepoint: pos_integer,
          advance: non_neg_integer,
          bbox: {{integer, integer, integer, integer}},
          ops: [op]
        }}

  @glyphs [
{entries}
  ]
  @names Keyword.keys(@glyphs)

  @doc "Font units per em."
  def units_per_em, do: {upem}

  @doc "Distance between the centres of adjacent staff lines, in font units."
  def staff_space, do: {space}

  @doc "Staff line thickness, in font units."
  def staff_line_thickness, do: {thickness}

  @doc "The y of the bottom staff line's centre, in font units."
  def staff_bottom, do: {bottom}

  @doc "The glyph names `glyph/1` knows."
  def names, do: @names

  @doc "A glyph's outline, advance width and bounding box."
  @spec glyph(atom) :: glyph
  def glyph(name)

  for {{name, glyph}} <- @glyphs do
    ops =
      for [_, cmd, args] <- Regex.scan(~r/([MLQZ])([^MLQZ]*)/, glyph.path) do
        nums =
          Enum.map(String.split(args), fn s ->
            case Integer.parse(s) do
              {{n, ""}} -> n
              _ -> String.to_float(s)
            end
          end)

        case {{cmd, nums}} do
          {{"Z", []}} -> :z
          {{"M", [x, y]}} -> {{:m, x, y}}
          {{"L", [x, y]}} -> {{:l, x, y}}
          {{"Q", [cx, cy, x, y]}} -> {{:q, cx, cy, x, y}}
        end
      end

    def glyph(unquote(name)) do
      unquote(Macro.escape(glyph |> Map.delete(:path) |> Map.put(:ops, ops)))
    end
  end
end
'''

if __name__ == "__main__":
    main()
